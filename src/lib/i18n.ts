export const messages: Record<Locale, Record<string, string>> = { en, es }

export function t(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const raw = messages[locale]?.[key] ?? messages.en[key] ?? key
  if (!params) return raw
  return raw.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ''))
}

export function translateError(locale: Locale, message: string): string {
  const m = message.toLowerCase()
  if (/wrong pin/.test(m)) return t(locale, 'err.wrongPin')
  if (/private to/.test(m) || /parents only/.test(m) || /invited caregivers/.test(m) || /cuidadores invitados/.test(m)) return t(locale, 'err.private')
  if (/not configured/.test(m)) return t(locale, 'err.noPin')
  if (/too many/.test(m)) return t(locale, 'err.tooMany')
  if (/sign in required/.test(m)) return t(locale, 'err.signIn')
  return message || t(locale, 'err.generic')
}

